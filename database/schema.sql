-- ─── 1. TABLA DE PERFILES ────────────────────────────────────
-- Se vincula automáticamente al Auth de Supabase via trigger
create table if not exists profiles (
  id uuid references auth.users on delete cascade primary key,
  username text unique,
  avatar_url text,
  full_name text,
  preferred_genres int[],        -- IDs de géneros TMDB: [28, 12]
  preferred_providers int[],     -- IDs de plataformas TMDB: [8, 337]
  has_completed_onboarding boolean default false,
  updated_at timestamp with time zone default now()
);

alter table profiles enable row level security;

create policy "profiles_select_own" on profiles
  for select to authenticated using (auth.uid() = id);

create policy "profiles_insert_own" on profiles
  for insert to authenticated with check (auth.uid() = id);

create policy "profiles_update_own" on profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);


-- ─── 2. TABLA DE INTERACCIONES ───────────────────────────────
-- Núcleo del algoritmo: registra cómo el usuario se comporta con cada película
create table if not exists interactions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users on delete cascade not null,
  movie_id bigint not null,
  genre_ids int[] not null default '{}',  -- Géneros TMDB de la película
  watch_time int not null default 0,      -- Segundos reales vistos
  is_full_watch boolean not null default false,  -- ¿Vio el tráiler completo?
  is_fast_scroll boolean not null default false, -- ¿Pasó en menos de 2 s?
  is_interested boolean not null default false,  -- ¿Le dio like / watchlist?
  created_at timestamp with time zone default now() not null
);

alter table interactions enable row level security;

create policy "interactions_select_own" on interactions
  for select to authenticated using (auth.uid() = user_id);

create policy "interactions_insert_own" on interactions
  for insert to authenticated with check (auth.uid() = user_id);

create policy "interactions_update_own" on interactions
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);


