-- ─── A. User preferred genres (weighted) ──────────────────────────
-- Score: like/watchlist=15, full trailer=8, >60s=5, >30s=3, >10s=1, fast scroll=-5
create or replace function get_user_genre_preferences(user_uuid uuid)
returns table (genre_id int, score bigint) as $$
begin
  return query
  select
    unnest(genre_ids) as genre_id,
    sum(
      case
        when is_interested then 15
        when is_full_watch then 8
        when is_fast_scroll then -5
        when watch_time >= 60 then 5
        when watch_time >= 30 then 3
        when watch_time >= 10 then 1
        else 0
      end
    ) as total_score
  from interactions
  where user_id = user_uuid
    and created_at > now() - interval '60 days'
  group by genre_id
  having sum(
    case
      when is_interested then 15
      when is_full_watch then 8
      when is_fast_scroll then -5
      when watch_time >= 60 then 5
      when watch_time >= 30 then 3
      when watch_time >= 10 then 1
      else 0
    end
  ) > 0
  order by total_score desc;
end;
$$ language plpgsql security definer;


-- ─── B. Top N recommended genre IDs (for client-side calls) ──────────
create or replace function get_recommended_genre_ids(
  user_uuid uuid,
  top_n int default 5,
  lookback_days int default 60
)
returns int[] as $$
declare
  result int[];
begin
  select array(
    select genre_id
    from (
      select
        unnest(genre_ids) as genre_id,
        sum(
          case
            when is_interested then 15
            when is_full_watch then 8
            when is_fast_scroll then -5
            when watch_time >= 60 then 5
            when watch_time >= 30 then 3
            when watch_time >= 10 then 1
            else 0
          end
        ) as score
      from interactions
      where user_id = user_uuid
        and created_at > now() - (lookback_days || ' days')::interval
      group by genre_id
    ) sub
    where score > 0
    order by score desc
    limit top_n
  ) into result;

  return coalesce(result, array[]::int[]);
end;
$$ language plpgsql security definer;


-- ─── C. Already-seen movie IDs (to exclude from feed) ───────────────
create or replace function get_seen_movie_ids(
  user_uuid uuid,
  limit_n int default 500
)
returns bigint[] as $$
  select array(
    select distinct movie_id
    from interactions
    where user_id = user_uuid
    order by movie_id
    limit limit_n
  );
$$ language sql security definer;


