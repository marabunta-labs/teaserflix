-- ============================================================
-- TEASERFLIX — current state of the `teaserflix` schema
-- Shared Supabase project ("shared", one schema per app). This file is the
-- CURRENT state (not stacked migrations) and mirrors marabunta-db/sql/20_teaserflix_schema.sql
-- (+ 22_teaserflix_merge.sql, which only moves data). Change both together.
-- Run in the Supabase SQL Editor (or psql).
--
-- Notes:
--  * No trigger on auth.users: auth is shared by all apps, so the app creates
--    the user's profile itself on first use.
--  * The client must use { db: { schema: 'teaserflix' } } and the schema must be
--    exposed in the API settings (PostgREST "Exposed schemas").
-- ============================================================

create schema if not exists teaserflix;
set search_path = teaserflix, extensions, public;

-- API roles can enter the schema and get privileges on what is created here
-- (RLS and the policies below decide what they actually see).
grant usage on schema teaserflix to anon, authenticated, service_role;
alter default privileges in schema teaserflix grant all on tables to anon, authenticated, service_role;
alter default privileges in schema teaserflix grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema teaserflix grant all on functions to anon, authenticated, service_role;


-- ─── 1. PROFILES TABLE ────────────────────────────────────────
create table if not exists profiles (
  id uuid references auth.users on delete cascade primary key,
  username text unique,
  avatar_url text,
  full_name text,
  preferred_genres int[],        -- TMDB genre IDs e.g. [28, 12]
  preferred_providers int[],     -- TMDB platform IDs e.g. [8, 337]
  has_completed_onboarding boolean default false,
  updated_at timestamp with time zone default now()
);

alter table profiles enable row level security;

